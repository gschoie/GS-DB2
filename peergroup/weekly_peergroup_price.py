def main():
    print("📈 [1/4] 야후 파이낸스 데이터 수집 시작...")

    today = datetime.today()
    start_date = (today - timedelta(days=4*365)).strftime('%Y-%m-%d')
    end_date = (today + timedelta(days=1)).strftime('%Y-%m-%d')

    history_dict = {}
    dashboard_data = []
    exchange_rates_to_usd = {'USD': 1.0}

    for comp in TARGET_COMPANIES:
        ticker = comp["ticker"]
        name = comp["name"]
        ind = comp["industry"]
        c_sub = comp["category_sub"]
        reg = comp["region"]
        print(f"🚀 [{ind} > {c_sub} > {reg}] {name} ({ticker}) 수집 중...")

        try:
            stock = yf.Ticker(ticker)
            hist = stock.history(start=start_date, end=end_date)
            info = stock.info

            if hist.empty:
                print(f"⚠️ {name} 데이터 빈 값 발생. 건너뜁니다.")
                continue

            hist.index = pd.to_datetime(hist.index).tz_localize(None).normalize()
            hist = hist[~hist.index.duplicated(keep='last')]

            three_years_ago = hist.index[-1] - timedelta(days=3*365)
            hist_3y = hist.loc[hist.index >= three_years_ago]

            hist_col_name = f"{name}({ticker})"
            history_dict[hist_col_name] = hist_3y['Close']

            current_price = hist['Close'].iloc[-1]
            latest_date = hist.index[-1]

            raw_mc = info.get('marketCap')
            if not raw_mc or raw_mc == 0:
                shares = info.get('sharesOutstanding')
                price = info.get('currentPrice')
                if shares and price:
                    raw_mc = shares * price
                else:
                    raw_mc = 0

            currency = info.get('currency', 'USD')
            if not raw_mc or raw_mc == 0:
                mc_str = "N/A"
            else:
                if currency not in exchange_rates_to_usd:
                    try:
                        ex_ticker = f"{currency}USD=X"
                        ex_data = yf.Ticker(ex_ticker).history(period="1d")
                        if not ex_data.empty:
                            exchange_rates_to_usd[currency] = ex_data['Close'].iloc[-1]
                        else:
                            exchange_rates_to_usd[currency] = 1.0
                    except:
                        exchange_rates_to_usd[currency] = 1.0

                mc_usd = raw_mc * exchange_rates_to_usd[currency]
                val_in_billion_usd = mc_usd / 1_000_000_000
                mc_str = f"{val_in_billion_usd:,.2f}"

            def calculate_return(days_ago):
                target_date = latest_date - timedelta(days=days_ago)
                past_data = hist.loc[hist.index <= target_date]
                if past_data.empty: return None
                past_price = past_data['Close'].iloc[-1]
                return (current_price - past_price) / past_price

            ret_1w = calculate_return(7)
            ret_1m = calculate_return(30)
            ret_3m = calculate_return(91)
            ret_1y = calculate_return(365)
            ret_3y = calculate_return(365*3)

            # YTD: 전년도 마지막 거래일 종가 대비 (연초대비 수익률)
            year_start = datetime(latest_date.year, 1, 1)
            prev_year_data = hist.loc[hist.index < year_start]
            if prev_year_data.empty:
                ret_ytd = None  # 올해 상장 등으로 전년도 종가가 없으면 공란
            else:
                ytd_base = prev_year_data['Close'].iloc[-1]
                ret_ytd = (current_price - ytd_base) / ytd_base

            # 52주 고점대비: 현재가 / 최근 52주 최고가 - 1 (0=고점, 음수=고점 아래)
            one_year_ago = latest_date - timedelta(days=365)
            last_1y_close = hist.loc[hist.index >= one_year_ago, 'Close']
            high_52w = last_1y_close.max()
            off_52w_high = (current_price / high_52w - 1) if (high_52w and high_52w > 0) else None

            dashboard_data.append([
                ind, c_sub, reg, name, ticker, mc_str, ret_1w, ret_1m, ret_3m, ret_ytd, "", ret_1y, ret_3y, off_52w_high, hist_col_name
            ])

        except Exception as e:
            print(f"❌ {name} 처리 중 오류 발생: {e}")

